//! Frozen Itanium builtin and terminal vocabulary, translated from `abi_mangle.h`. See NOTICE.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Builtin {
    Void,
    Bool,
    Char,
    SignedChar,
    UnsignedChar,
    Wchar,
    Char16,
    Char32,
    Short,
    UnsignedShort,
    Int,
    UnsignedInt,
    Long,
    UnsignedLong,
    LongLong,
    UnsignedLongLong,
    Int128,
    Uint128,
    Float,
    Double,
    LongDouble,
    Float16,
    Float32,
    Float32X,
    Float64,
    Float64X,
    StdFloat128,
    Float128,
    ComplexFloat,
    ComplexDouble,
    ComplexLongDouble,
    Nullptr,
    Bfloat16,
}
impl Builtin {
    #[must_use]
    pub fn from_word(word: &[u8]) -> Option<Self> {
        Some(match word {
            b"void" => Self::Void,
            b"bool" => Self::Bool,
            b"char" => Self::Char,
            b"schar" => Self::SignedChar,
            b"uchar" => Self::UnsignedChar,
            b"wchar" => Self::Wchar,
            b"char16" => Self::Char16,
            b"char32" => Self::Char32,
            b"short" => Self::Short,
            b"ushort" => Self::UnsignedShort,
            b"int" => Self::Int,
            b"uint" => Self::UnsignedInt,
            b"long" => Self::Long,
            b"ulong" => Self::UnsignedLong,
            b"longlong" => Self::LongLong,
            b"ulonglong" => Self::UnsignedLongLong,
            b"int128" => Self::Int128,
            b"uint128" => Self::Uint128,
            b"float" => Self::Float,
            b"double" => Self::Double,
            b"longdouble" => Self::LongDouble,
            b"float16" => Self::Float16,
            b"float32" => Self::Float32,
            b"float32x" => Self::Float32X,
            b"float64" => Self::Float64,
            b"float64x" => Self::Float64X,
            b"stdfloat128" => Self::StdFloat128,
            b"float128" => Self::Float128,
            b"complex-float" => Self::ComplexFloat,
            b"complex-double" => Self::ComplexDouble,
            b"complex-longdouble" => Self::ComplexLongDouble,
            b"nullptr" => Self::Nullptr,
            b"bfloat16" => Self::Bfloat16,
            _ => return None,
        })
    }
    #[must_use]
    pub fn entry(self) -> (&'static [u8], u8, bool) {
        match self {
            Self::Void => (b"v", 0, false),
            Self::Bool => (b"b", 1, true),
            Self::Char => (b"c", 8, false),
            Self::SignedChar => (b"a", 8, false),
            Self::UnsignedChar => (b"h", 8, true),
            Self::Wchar => (b"w", 32, false),
            Self::Char16 => (b"Ds", 16, true),
            Self::Char32 => (b"Di", 32, true),
            Self::Short => (b"s", 16, false),
            Self::UnsignedShort => (b"t", 16, true),
            Self::Int => (b"i", 32, false),
            Self::UnsignedInt => (b"j", 32, true),
            Self::Long => (b"l", 64, false),
            Self::UnsignedLong => (b"m", 64, true),
            Self::LongLong => (b"x", 64, false),
            Self::UnsignedLongLong => (b"y", 64, true),
            Self::Int128 => (b"n", 0, false),
            Self::Uint128 => (b"o", 0, true),
            Self::Float => (b"f", 0, false),
            Self::Double => (b"d", 0, false),
            Self::LongDouble => (b"e", 0, false),
            Self::Float16 => (b"DF16_", 0, false),
            Self::Float32 => (b"DF32_", 0, false),
            Self::Float32X => (b"DF32x", 0, false),
            Self::Float64 => (b"DF64_", 0, false),
            Self::Float64X => (b"DF64x", 0, false),
            Self::StdFloat128 => (b"DF128_", 0, false),
            Self::Float128 => (b"g", 0, false),
            Self::ComplexFloat => (b"Cf", 0, false),
            Self::ComplexDouble => (b"Cd", 0, false),
            Self::ComplexLongDouble => (b"Ce", 0, false),
            Self::Nullptr => (b"Dn", 0, false),
            Self::Bfloat16 => (b"DF16b", 0, false),
        }
    }
    #[must_use]
    pub fn substitutable(self) -> bool {
        matches!(
            self,
            Self::ComplexFloat | Self::ComplexDouble | Self::ComplexLongDouble
        )
    }
}

